<?php

declare(strict_types=1);

namespace App\Support;

use RuntimeException;
use SodiumException;

/**
 * Encrypts a backup file at rest, and decrypts it for a restore.
 *
 * §9 of the approved referral operating model (HR-OPS-REF-R1-001) requires "encrypted backups and tested
 * recovery procedures". Until this class existed the dump was a plain gzipped SQL script — a complete copy
 * of the clinical database in the clear, readable by anyone who obtained the file. The restore procedure was
 * proven on 22 November (`db:restore-drill`, 51 tables, 78 rows); the encryption was absent.
 *
 * **What it protects, stated so nobody over-reads it.** A key held in the same `.env` as the database
 * password protects a *copied* file: a backup downloaded over FTP, mailed to a colleague, left in a synced
 * folder, or lifted from a decommissioned disk. It does not protect against someone who already has the
 * application's environment, because they have the key. That limit is the reason the key is documented as an
 * operational secret with its own custody, rather than treated as a solved problem.
 *
 * **Format.** `HRBK1` magic, the 24-byte secretstream header, then length-prefixed records of
 * `sodium_crypto_secretstream_xchacha20poly1305` output. Each record carries its own authentication tag, so a
 * single flipped byte fails the pull rather than yielding a dump that restores to the wrong data. The final
 * record carries TAG_FINAL, so a truncated file is refused instead of half-restored. `secretstream` is used
 * rather than a single `openssl_encrypt` call because a multi-megabyte dump should not be held twice in
 * memory, and because it is the construct designed for exactly this: a stream, chunked, authenticated.
 *
 * **The key is not derived from a passphrase.** A passphrase needs a KDF with parameters that would have to
 * be stored beside the ciphertext and reviewed; a 32-byte random key generated by `db:backup --key` has no
 * parameters to get wrong. `sodium` is enabled on the shared host (panel inventory, 22 November), so this runs
 * where the backups are actually written.
 */
final class BackupCipher
{
    public const KEY_BYTES = SODIUM_CRYPTO_SECRETSTREAM_XCHACHA20POLY1305_KEYBYTES;

    /** Five ASCII bytes. A file without them is not one of ours, whatever its name. */
    public const MAGIC = 'HRBK1';

    private const HEADER_BYTES = SODIUM_CRYPTO_SECRETSTREAM_XCHACHA20POLY1305_HEADERBYTES;

    private const TAG_BYTES = SODIUM_CRYPTO_SECRETSTREAM_XCHACHA20POLY1305_ABYTES;

    /** 256 KiB: large enough that per-record overhead is irrelevant, small enough to bound memory. */
    private const CHUNK_BYTES = 262144;

    public function __construct(private readonly string $key)
    {
        if (strlen($key) !== self::KEY_BYTES) {
            throw new RuntimeException(sprintf(
                'An encryption key must be %d bytes; %d were supplied.',
                self::KEY_BYTES,
                strlen($key),
            ));
        }
    }

    /**
     * Build from the value of `BACKUP_ENCRYPTION_KEY`.
     *
     * Standard base64, as `db:backup --key` prints it. A URL-safe alphabet would also decode, but accepting
     * both silently is how two installations end up with keys that look different and mean the same thing;
     * the generator and the parser agree on one alphabet.
     */
    public static function fromBase64(string $encoded): self
    {
        $trimmed = trim($encoded);

        if ($trimmed === '') {
            throw new RuntimeException(
                'BACKUP_ENCRYPTION_KEY is not set, so a backup cannot be encrypted. Generate one with '
                . '`php bin/console db:backup --key` and store it where the application can read it but a '
                . 'backup file cannot.',
            );
        }

        try {
            $raw = sodium_base642bin($trimmed, SODIUM_BASE64_VARIANT_ORIGINAL);
        } catch (SodiumException) {
            throw new RuntimeException('BACKUP_ENCRYPTION_KEY is not valid base64.');
        }

        return new self($raw);
    }

    /** A fresh key, base64, for `BACKUP_ENCRYPTION_KEY`. */
    public static function generateKey(): string
    {
        return sodium_bin2base64(random_bytes(self::KEY_BYTES), SODIUM_BASE64_VARIANT_ORIGINAL);
    }

    /** True when the file begins with our magic. Reads five bytes and no more. */
    public static function looksEncrypted(string $path): bool
    {
        $handle = @fopen($path, 'rb');

        if ($handle === false) {
            return false;
        }

        $magic = fread($handle, strlen(self::MAGIC));
        fclose($handle);

        return $magic === self::MAGIC;
    }

    /**
     * Encrypt $source into $target. The source is read in chunks and never held whole.
     *
     * The target is written directly; the caller is responsible for writing it somewhere a partial file
     * cannot be mistaken for a finished backup.
     */
    public function encryptFile(string $source, string $target): void
    {
        $in = @fopen($source, 'rb');

        if ($in === false) {
            throw new RuntimeException('Cannot read ' . $source . ' to encrypt it.');
        }

        $out = @fopen($target, 'wb');

        if ($out === false) {
            fclose($in);

            throw new RuntimeException('Cannot write ' . $target . '.');
        }

        try {
            [$state, $header] = sodium_crypto_secretstream_xchacha20poly1305_init_push($this->key);

            $this->writeAll($out, self::MAGIC . $header);

            // The loop leaves only through the `break` below, which is reached only on the record that
            // carries TAG_FINAL, or through an exception. There is no third exit to guard against.
            while (true) {
                $chunk = fread($in, self::CHUNK_BYTES);

                if ($chunk === false) {
                    throw new RuntimeException('Cannot read ' . $source . ' to encrypt it.');
                }

                $final = feof($in);

                if ($chunk === '' && !$final) {
                    throw new RuntimeException('Read returned no bytes before the end of ' . $source . '.');
                }

                $tag = $final
                    ? SODIUM_CRYPTO_SECRETSTREAM_XCHACHA20POLY1305_TAG_FINAL
                    : SODIUM_CRYPTO_SECRETSTREAM_XCHACHA20POLY1305_TAG_MESSAGE;

                $cipher = sodium_crypto_secretstream_xchacha20poly1305_push($state, $chunk, '', $tag);

                $this->writeAll($out, pack('N', strlen($cipher)) . $cipher);

                if ($final) {
                    break;
                }
            }
        } finally {
            fclose($in);
            fclose($out);
        }
    }

    /**
     * Decrypt a whole file into a string.
     *
     * The restore path already materialises the SQL script in memory before splitting it into statements, so
     * this adds no new ceiling; the temporary stream spills to disk past 2 MiB rather than growing the string
     * twice.
     */
    public function decryptContents(string $path): string
    {
        $in = @fopen($path, 'rb');

        if ($in === false) {
            throw new RuntimeException('Cannot read ' . $path . '.');
        }

        try {
            $magic = fread($in, strlen(self::MAGIC));
            if ($magic !== self::MAGIC) {
                throw new RuntimeException($path . ' is not a HakimeRAD encrypted backup.');
            }

            $header = fread($in, self::HEADER_BYTES);
            if (!is_string($header) || strlen($header) !== self::HEADER_BYTES) {
                throw new RuntimeException($path . ' is truncated: the header is incomplete.');
            }

            try {
                $state = sodium_crypto_secretstream_xchacha20poly1305_init_pull($header, $this->key);
            } catch (SodiumException) {
                throw new RuntimeException(
                    $path . ' cannot be decrypted with this key. The header does not authenticate, which means '
                    . 'the key is wrong or the file is corrupt.',
                );
            }

            $buffer = fopen('php://temp/maxmemory:2097152', 'w+b');
            if ($buffer === false) {
                throw new RuntimeException('Cannot open a temporary buffer.');
            }

            try {
                $sawFinal = false;

                while (true) {
                    $prefix = fread($in, 4);

                    if ($prefix === false || $prefix === '') {
                        break;
                    }

                    if (strlen($prefix) !== 4) {
                        throw new RuntimeException($path . ' is truncated: a record length is incomplete.');
                    }

                    /** @var array{1: int} $unpacked */
                    $unpacked = unpack('N', $prefix);
                    $length = $unpacked[1];

                    if ($length < self::TAG_BYTES || $length > self::CHUNK_BYTES + self::TAG_BYTES) {
                        throw new RuntimeException($path . ' is corrupt: a record length is out of range.');
                    }

                    $cipher = fread($in, $length);
                    if (!is_string($cipher) || strlen($cipher) !== $length) {
                        throw new RuntimeException($path . ' is truncated: a record is incomplete.');
                    }

                    $result = sodium_crypto_secretstream_xchacha20poly1305_pull($state, $cipher);

                    if ($result === false) {
                        throw new RuntimeException(
                            $path . ' failed authentication. Either the key is wrong or the file was altered '
                            . 'after it was written; a restore from it would not be the database it claims to be.',
                        );
                    }

                    fwrite($buffer, $result[0]);

                    if ($result[1] === SODIUM_CRYPTO_SECRETSTREAM_XCHACHA20POLY1305_TAG_FINAL) {
                        $sawFinal = true;

                        break;
                    }
                }

                if (!$sawFinal) {
                    throw new RuntimeException(
                        $path . ' ends without a final record, so it is a partial file rather than a backup.',
                    );
                }

                rewind($buffer);
                $contents = stream_get_contents($buffer);

                if (!is_string($contents)) {
                    throw new RuntimeException('Cannot read the decrypted buffer.');
                }

                return $contents;
            } finally {
                fclose($buffer);
            }
        } finally {
            fclose($in);
        }
    }

    /** @param resource $handle */
    private function writeAll($handle, string $data): void
    {
        $written = fwrite($handle, $data);

        if ($written !== strlen($data)) {
            throw new RuntimeException('Cannot write the encrypted backup; the disk may be full.');
        }
    }
}
